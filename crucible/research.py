"""Versioned public research records, with narrowly scoped recovery evidence.

Contributions are deliberate, unreviewed claims. Their authors may explicitly
attach owned successful submissions as narrowly scoped evidence. An attached
receipt says nothing about the method, resource estimates, novelty, or the
finding's general claim. Successful runs never create findings automatically.
"""
import base64
import json
import math
from typing import Literal
from urllib.parse import urlsplit
from uuid import UUID, uuid4

from fastapi import HTTPException, Query, Request
from pydantic import BaseModel, ConfigDict, Field, field_validator
from sqlalchemy import Float, ForeignKey, Index, Integer, JSON, String, Text, UniqueConstraint, and_, func, or_, select
from sqlalchemy.orm import Mapped, mapped_column

from . import kem
from .db import Base, Challenge, Submission, User
from .legacy import teaching_dh_v1


class Contribution(Base):
    __tablename__ = "contributions"
    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    author_id: Mapped[str] = mapped_column(ForeignKey("users.id"), index=True)
    created_at: Mapped[float] = mapped_column(Float)


class ContributionRevision(Base):
    __tablename__ = "contribution_revisions"
    __table_args__ = (
        UniqueConstraint("contribution_id", "revision", name="uq_contribution_revision"),
        Index("ix_contribution_target_time", "target_id", "created_at"),
    )
    id: Mapped[str] = mapped_column(String(36), primary_key=True)
    contribution_id: Mapped[str] = mapped_column(ForeignKey("contributions.id"), index=True)
    revision: Mapped[int] = mapped_column(Integer)
    created_at: Mapped[float] = mapped_column(Float)
    target_id: Mapped[str] = mapped_column(String(100))
    target_version: Mapped[str] = mapped_column(String(32))
    profile_ids: Mapped[list] = mapped_column(JSON)
    title: Mapped[str] = mapped_column(String(200))
    claim: Mapped[str] = mapped_column(Text)
    conditions: Mapped[str] = mapped_column(Text)
    body: Mapped[str] = mapped_column(Text)
    model: Mapped[str] = mapped_column(String(32))
    evidence_kind: Mapped[str] = mapped_column(String(32))
    time_cost: Mapped[str | None] = mapped_column(Text, nullable=True)
    memory_cost: Mapped[str | None] = mapped_column(Text, nullable=True)
    success_probability: Mapped[str | None] = mapped_column(Text, nullable=True)
    artifact_url: Mapped[str | None] = mapped_column(Text, nullable=True)
    related_contribution_id: Mapped[str | None] = mapped_column(ForeignKey("contributions.id"), nullable=True, index=True)
    verified_submission_id: Mapped[str | None] = mapped_column(ForeignKey("submissions.id"), nullable=True)


def targets():
    """An explicit, extensible catalogue; no uploads become executable targets."""
    profiles = [{**{key: item[key] for key in ("id", "name", "parameter_bits", "parameter_label")},
                 "instance_size": item.get("instance_size", item["parameter_bits"])}
                for item in kem.manifests()]
    scheme_versions = [{"version": kem.SCHEME_VERSION, "profiles": profiles}]
    if teaching_dh_v1.SCHEME_VERSION != kem.SCHEME_VERSION:
        legacy_profiles = [{**{key: item[key] for key in ("id", "name", "parameter_bits", "parameter_label")},
                            "instance_size": item["parameter_bits"]}
                           for item in teaching_dh_v1.manifests()]
        scheme_versions.append({"version": teaching_dh_v1.SCHEME_VERSION, "profiles": legacy_profiles})
    return [
        {"id": kem.SCHEME_ID, "name": "Teaching DH-KEM", "kind": "scheme", "version": kem.SCHEME_VERSION,
         "summary": "An executable, deliberately weak KEM for studying recovery methods and the research workflow.",
         "definition": "Key generation publishes g^x; encapsulation publishes g^r and derives a shared secret from g^(xr) and the transcript. See the pinned reference specification for the full encoding and distribution. This teaching construction claims no security guarantee.",
         "related_targets": [{"id": "finite-field-dlog", "relationship": "A discrete-log solution supplies an attack on this KEM. No converse or formal security reduction is claimed."}],
         "profiles": profiles, "versions": scheme_versions},
        {"id": "finite-field-dlog", "name": "Finite-field discrete logarithm", "kind": "assumption", "version": "1",
         "summary": "A mathematical problem page, not an assertion that the listed small groups are hard.",
         "definition": "Given a prime p, a prime-order subgroup generated by g with order q, and h = g^x mod p, find x modulo q. A hardness assumption additionally needs a distribution, parameter family, adversary model, and resource bound. No hardness claim is made for these teaching profiles.",
         "related_targets": [{"id": kem.SCHEME_ID, "relationship": "Solving a discrete logarithm of the reference KEM public key enables recovery. This is one attack route, not a claimed equivalence of security notions."}],
         "profiles": profiles, "versions": [{"version": "1", "profiles": profiles}]},
    ]


class ContributionInput(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True, allow_inf_nan=False)
    target_id: str = Field(min_length=1, max_length=100)
    target_version: str = Field(min_length=1, max_length=32)
    profile_ids: list[str] = Field(default_factory=list, max_length=20)
    title: str = Field(min_length=1, max_length=200)
    claim: str = Field(min_length=1, max_length=5000)
    conditions: str = Field(min_length=1, max_length=5000)
    body: str = Field(min_length=1, max_length=15000)
    model: Literal["classical", "quantum", "mixed", "not-applicable"]
    evidence_kind: Literal["argument", "heuristic", "experiment", "mixed"]
    time_cost: str | None = Field(default=None, max_length=1000)
    memory_cost: str | None = Field(default=None, max_length=1000)
    success_probability: str | None = Field(default=None, max_length=1000)
    artifact_url: str | None = Field(default=None, max_length=2000)
    related_contribution_id: UUID | None = None
    submission_id: UUID | None = None

    @field_validator("time_cost", "memory_cost", "success_probability", "artifact_url")
    @classmethod
    def optional_text(cls, value):
        return value or None

    @field_validator("artifact_url")
    @classmethod
    def safe_link(cls, value):
        if value is None:
            return None
        try:
            parsed = urlsplit(value)
            valid = (parsed.scheme == "https" and bool(parsed.hostname) and
                     parsed.username is None and parsed.password is None and
                     "\\" not in value and not any(character.isspace() or ord(character) < 32 for character in value))
            parsed.port  # Invalid ports are not accepted as links.
        except ValueError:
            valid = False
        if not valid:
            raise ValueError("Artifact links must be HTTPS URLs without credentials.")
        return value


class RevisionInput(ContributionInput):
    expected_revision: int = Field(ge=1, strict=True)


def _target(target_id):
    result = next((item for item in targets() if item["id"] == target_id), None)
    if result is None:
        raise HTTPException(404, "Research target not found.")
    return result


def _validated_values(body, session, user_id, contribution_id=None):
    target = _target(body.target_id)
    version = next((item for item in target["versions"] if item["version"] == body.target_version), None)
    if version is None:
        raise HTTPException(422, "Choose the registered target version.")
    allowed_profiles = {item["id"] for item in version["profiles"]}
    if len(set(body.profile_ids)) != len(body.profile_ids) or any(item not in allowed_profiles for item in body.profile_ids):
        raise HTTPException(422, "Choose distinct profiles belonging to this target.")
    adapter = teaching_dh_v1 if body.target_id == kem.SCHEME_ID and body.target_version == "1" else kem
    for profile_id in body.profile_ids:
        adapter.get_manifest(profile_id)
    related = str(body.related_contribution_id) if body.related_contribution_id else None
    if related:
        if related == contribution_id:
            raise HTTPException(422, "A follow-up must link a different contribution.")
        if session.get(Contribution, related) is None:
            raise HTTPException(404, "Related contribution not found.")
    submission_id = str(body.submission_id) if body.submission_id else None
    if submission_id:
        submission = session.get(Submission, submission_id)
        if not submission or submission.user_id != user_id:
            raise HTTPException(404, "Supporting recovery not found.")
        challenge = session.get(Challenge, submission.challenge_id)
        if (not submission.correct or not challenge or challenge.user_id != user_id or
                not challenge.issued_at <= submission.received_at < challenge.ends_at):
            raise HTTPException(422, "Only a correct, on-time recovery may be attached as checked instance evidence.")
        if (body.target_id != challenge.scheme_id or body.target_version != challenge.scheme_version or
                challenge.profile_id not in body.profile_ids):
            raise HTTPException(422, "The finding target, version, and selected profiles must cover the attached recovery.")
    values = body.model_dump(exclude={"expected_revision", "related_contribution_id", "submission_id"})
    values["related_contribution_id"] = related
    values["verified_submission_id"] = submission_id
    return values


def _verification(session, revision):
    if not revision.verified_submission_id:
        return None
    submission = session.get(Submission, revision.verified_submission_id)
    challenge = session.get(Challenge, submission.challenge_id) if submission else None
    if not submission or not submission.correct or not challenge:
        return None
    return {"submission_id": submission.id, "challenge_id": challenge.id,
            "scheme_id": challenge.scheme_id, "scheme_version": challenge.scheme_version, "profile_id": challenge.profile_id,
            "received_at": submission.received_at, "elapsed_seconds": submission.elapsed_seconds,
            "scope": "The server checked the complete shared secret for this one instance before its deadline. This finding remains unreviewed: the method, compute estimates, novelty, and general security claims are not independently verified."}


def _revision_data(session, revision):
    fields = ("id", "revision", "created_at", "target_id", "target_version", "profile_ids", "title", "claim",
              "conditions", "body", "model", "evidence_kind", "time_cost", "memory_cost", "success_probability",
              "artifact_url", "related_contribution_id")
    verification = _verification(session, revision)
    return {**{field: getattr(revision, field) for field in fields},
            "submission_id": revision.verified_submission_id,
            "review_status": "unreviewed", "verification": verification}


def _record_data(session, record, revision=None, author=None, *, history=False, before_revision=None, limit=20):
    if revision is None:
        revision = session.scalar(select(ContributionRevision).where(ContributionRevision.contribution_id == record.id)
                                  .order_by(ContributionRevision.revision.desc()).limit(1))
    author = author or session.get(User, record.author_id)
    result = {"id": record.id, "author": {"id": author.id, "handle": author.handle},
              "created_at": record.created_at, "updated_at": revision.created_at,
              "editable": True, "latest": _revision_data(session, revision)}
    if history:
        query = select(ContributionRevision).where(ContributionRevision.contribution_id == record.id)
        if before_revision is not None:
            query = query.where(ContributionRevision.revision < before_revision)
        revisions = session.scalars(query.order_by(ContributionRevision.revision.desc()).limit(limit + 1)).all()
        more, page = len(revisions) > limit, revisions[:limit]
        result["revisions"] = [_revision_data(session, item) for item in page]
        result["next_before_revision"] = page[-1].revision if more else None
    return result


def _cursor(at, identifier):
    return base64.urlsafe_b64encode(json.dumps([at, identifier], separators=(",", ":")).encode()).decode().rstrip("=")


def _read_cursor(value):
    try:
        at, identifier = json.loads(base64.urlsafe_b64decode(value + "=" * (-len(value) % 4)))
        if (isinstance(at, bool) or not isinstance(at, (float, int)) or not math.isfinite(at)
                or not isinstance(identifier, str)):
            raise ValueError()
        return at, str(UUID(identifier))
    except (ValueError, TypeError, UnicodeDecodeError):
        raise HTTPException(422, "Invalid contribution page cursor.")


def register_routes(app, db, settings, clock, user_for, throttle):
    @app.get("/api/targets")
    def get_targets():
        return {"targets": targets()}

    @app.get("/api/contributions")
    def list_contributions(target_id: str | None = Query(default=None, max_length=100),
                           limit: int = Query(default=20, ge=1, le=100),
                           before: str | None = Query(default=None, max_length=256)):
        if target_id:
            _target(target_id)
        cursor = _read_cursor(before) if before else None
        latest = select(ContributionRevision.contribution_id.label("root"),
                        func.max(ContributionRevision.revision).label("number")).group_by(ContributionRevision.contribution_id).subquery()
        query = (select(Contribution, ContributionRevision, User)
                 .join(ContributionRevision, ContributionRevision.contribution_id == Contribution.id)
                 .join(latest, and_(latest.c.root == Contribution.id, latest.c.number == ContributionRevision.revision))
                 .join(User, User.id == Contribution.author_id))
        if target_id:
            query = query.where(ContributionRevision.target_id == target_id)
        if cursor:
            at, identifier = cursor
            query = query.where(or_(ContributionRevision.created_at < at,
                and_(ContributionRevision.created_at == at, Contribution.id < identifier)))
        query = query.order_by(ContributionRevision.created_at.desc(), Contribution.id.desc()).limit(limit + 1)
        with db.transaction() as session:
            rows = session.execute(query).all()
            more, page = len(rows) > limit, rows[:limit]
            return {"contributions": [_record_data(session, record, revision, author) for record, revision, author in page],
                    "next_before": _cursor(page[-1][1].created_at, page[-1][0].id) if more else None}

    @app.get("/api/contributions/{contribution_id}")
    def get_contribution(contribution_id: UUID, before_revision: int | None = Query(default=None, ge=1, le=2147483647),
                         limit: int = Query(default=20, ge=1, le=50)):
        with db.transaction() as session:
            record = session.get(Contribution, str(contribution_id))
            if record is None:
                raise HTTPException(404, "Contribution not found.")
            return {"contribution": _record_data(session, record, history=True,
                                                 before_revision=before_revision, limit=limit)}

    @app.post("/api/contributions")
    def create_contribution(body: ContributionInput, request: Request):
        throttle(request, "contribution-write", 30, 3600)
        with db.transaction(write=True) as session:
            user = user_for(request, session, mutation=True)
            session.execute(select(User.id).where(User.id == user.id).with_for_update())
            values = _validated_values(body, session, user.id)
            record = Contribution(id=str(uuid4()), author_id=user.id, created_at=clock())
            session.add(record)
            session.flush()
            revision = ContributionRevision(id=str(uuid4()), contribution_id=record.id, revision=1,
                                            created_at=record.created_at, **values)
            session.add(revision)
            session.flush()
            return {"contribution": _record_data(session, record, revision, user)}

    @app.post("/api/contributions/{contribution_id}/revisions")
    def revise_contribution(contribution_id: UUID, body: RevisionInput, request: Request):
        throttle(request, "contribution-write", 30, 3600)
        with db.transaction(write=True) as session:
            user = user_for(request, session, mutation=True)
            session.execute(select(User.id).where(User.id == user.id).with_for_update())
            record = session.get(Contribution, str(contribution_id))
            if record is None:
                raise HTTPException(404, "Contribution not found.")
            if record.author_id != user.id:
                raise HTTPException(403, "Only the author may revise this contribution.")
            latest = session.scalar(select(ContributionRevision).where(ContributionRevision.contribution_id == record.id)
                                    .order_by(ContributionRevision.revision.desc()).limit(1))
            if body.expected_revision != latest.revision:
                raise HTTPException(409, "A newer revision exists. Refresh before revising.")
            values = _validated_values(body, session, user.id, record.id)
            revision = ContributionRevision(id=str(uuid4()), contribution_id=record.id, revision=latest.revision + 1,
                                            created_at=clock(), **values)
            session.add(revision)
            session.flush()
            return {"contribution": _record_data(session, record, revision, user)}
